/* The world for the iPhone app, from the computer app's map, the way the extension
   gets it (chrome-extension/scripts/sync-world.mjs): one world, read here.

     node ios-app/scripts/sync-world.mjs

   Written as plain text the app parses at start: a Swift dictionary this large
   takes the compiler minutes. */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, "..", "..", "desktop-app", "src", "components", "connect", "worldDots.ts");
const OUT = join(HERE, "..", "HProxy", "WorldData.swift");

const ts = readFileSync(SOURCE, "utf8");
const block = ts.slice(ts.indexOf("COUNTRY_CELLS"), ts.indexOf("OTHER_LAND"));
const countries = [...block.matchAll(/^\s*([a-z]{2}): "([^"]+)"/gm)].map((m) => `${m[1]}=${m[2]}`);
const other = /OTHER_LAND = "([^"]*)"/.exec(ts)?.[1] ?? "";
const cols = Number(/cols: (\d+)/.exec(ts)?.[1]);
const rows = Number(/rows: (\d+)/.exec(ts)?.[1]);

writeFileSync(
  OUT,
  `// GENERATED by ios-app/scripts/sync-world.mjs from the computer app's worldDots.ts
// (Natural Earth 1:50m, public domain). Do not edit by hand.

enum WorldData {
    static let cols = ${cols}
    static let rows = ${rows}
    static let otherLand = "${other}"
    static let countries = "${countries.join(";")}"
}
`,
);
console.log(`world: ${countries.length} countries`);
